export function Poets() {
  const [activeFilter, setActiveFilter] = useState('Все');
  const [expandedPoet, setExpandedPoet] = useState<string | null>(null);

  const filters = ['Все', 'Гилея', 'Эго-футуризм', 'Центрифуга'];
  const filterColors: Record<string, string> = {
    'Все': '#6C76F0',
    'Гилея': '#E05555',
    'Эго-футуризм': '#E8C84A',
    'Центрифуга': '#50B87A',
  };

  const filteredPoets = poets.filter((poet) => {
    if (activeFilter === 'Все') return true;
    return poet.group === activeFilter;
  });

  const togglePoet = (name: string) => {
    setExpandedPoet(expandedPoet === name ? null : name);
  };

  return (
    <section id="poets" className="py-24 md:py-32 px-6" style={{ backgroundColor: 'var(--c-surface)' }}>
      <div className="max-w-7xl mx-auto">
        {/* Section header */}
        <div className="mb-12 text-center">
          <div className="text-[11px] tracking-[0.2em] uppercase mb-4" style={{ fontFamily: 'var(--font-body)', color: '#6C76F0' }}>
            ПЕРСОНАЛИИ
          </div>
          <h2 className="text-[52px] mb-4" style={{ fontFamily: 'var(--font-display)', fontWeight: 700 }}>
            Поэты
          </h2>
          <p className="text-[18px] mb-2" style={{ fontFamily: 'var(--font-body)', color: 'var(--c-text-muted)' }}>
            Голоса русского авангарда
          </p>
          <p className="text-[15px] mb-8" style={{ fontFamily: 'var(--font-body)', color: 'var(--c-text-muted)' }}>
            Нажмите на карточку, чтобы прочитать биографию
          </p>

          {/* Filter pills */}
          <div className="flex flex-wrap gap-3 justify-center">
            {filters.map((filter) => (
              <button
                key={filter}
                onClick={() => { setActiveFilter(filter); setExpandedPoet(null); }}
                className="px-6 py-2 rounded-full border-2 transition-all"
                style={{
                  fontFamily: 'var(--font-body)',
                  fontWeight: 600,
                  fontSize: '14px',
                  borderColor: activeFilter === filter ? filterColors[filter] : 'var(--c-border)',
                  backgroundColor: activeFilter === filter ? filterColors[filter] : 'transparent',
                  color: activeFilter === filter ? 'var(--c-bg)' : 'var(--c-text)'
                }}
              >
                {filter}
              </button>
            ))}
          </div>
        </div>

        {/* Poets grid */}
        <style>{`
          @keyframes poetIn { from{opacity:0;transform:translateY(24px)} to{opacity:1;transform:translateY(0)} }
          @keyframes poetFlip { 0%{transform:rotateY(0)} 100%{transform:rotateY(180deg)} }
          .poet-card-inner { position:relative; transform-style:preserve-3d; transition:transform 0.6s cubic-bezier(0.4,0,0.2,1); }
          .poet-card-inner.flipped { transform:rotateY(180deg); }
          .poet-card-front,.poet-card-back { backface-visibility:hidden; -webkit-backface-visibility:hidden; }
          .poet-card-back { position:absolute; inset:0; transform:rotateY(180deg); border-radius:8px; overflow:hidden; }
        `}</style>
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {filteredPoets.map((poet, poetIdx) => {
            const isExpanded = expandedPoet === poet.name;
            return (
              <div
                key={poet.name}
                className={`rounded-lg transition-all duration-300 cursor-pointer ${isExpanded ? 'lg:col-span-3' : ''}`}
                style={{
                  backgroundColor: 'var(--c-bg)',
                  boxShadow: isExpanded ? `0 0 0 2px ${poet.color}` : '0 4px 6px rgba(0,0,0,0.1)',
                  animation: `poetIn 0.5s cubic-bezier(0.22,1,0.36,1) ${poetIdx * 80}ms both`
                }}
                onClick={() => togglePoet(poet.name)}
              >
                {/* Card header – always visible */}
                <div className="p-6">
                  <div className="flex items-start gap-4">
                    {/* Avatar with hover zoom + expand zoom */}
                    <div
                      className="rounded-full overflow-hidden flex-shrink-0"
                      style={{
                        width: isExpanded ? '192px' : '96px',
                        height: isExpanded ? '192px' : '96px',
                        border: `2px solid ${poet.color}`,
                        flexShrink: 0,
                        transition: 'width 0.4s ease, height 0.4s ease, box-shadow 0.3s ease',
                        boxShadow: isExpanded ? `0 0 0 4px ${poet.color}50` : 'none'
                      }}
                      onMouseEnter={e => { if (!isExpanded) { (e.currentTarget as HTMLDivElement).style.boxShadow = `0 0 0 3px ${poet.color}60`; } }}
                      onMouseLeave={e => { if (!isExpanded) { (e.currentTarget as HTMLDivElement).style.boxShadow = 'none'; } }}
                    >
                      {poet.photo ? (
                        <img
                          src={poet.photo}
                          alt={poet.name}
                          className="w-full h-full object-cover object-top"
                          style={{ borderRadius: '50%' }}
                        />
                      ) : (
                        <div className="w-full h-full flex items-center justify-center" style={{ backgroundColor: 'var(--c-surface)' }}>
                          <User size={24} style={{ color: poet.color }} />
                        </div>
                      )}
                    </div>

                    <div className="flex-1 min-w-0">
                      <h3 className="text-[18px] mb-1" style={{ fontFamily: 'var(--font-display)', fontWeight: 700 }}>
                        {poet.name}
                      </h3>
                      <div className="text-[13px] mb-2" style={{ fontFamily: 'var(--font-body)', color: 'var(--c-text-muted)' }}>
                        {poet.years}
                      </div>
                      <span
                        className="inline-block px-3 py-1 rounded-full text-[11px]"
                        style={{ fontFamily: 'var(--font-body)', fontWeight: 600, backgroundColor: poet.color, color: 'var(--c-bg)' }}
                      >
                        {poet.tag}
                      </span>
                    </div>

                    <div style={{ color: 'var(--c-text-muted)', flexShrink: 0 }}>
                      {isExpanded ? <ChevronUp size={20} /> : <ChevronDown size={20} />}
                    </div>
                  </div>

                  {!isExpanded && (
                    <p className="mt-4 text-[14px] leading-[1.6]" style={{ fontFamily: 'var(--font-body)', color: 'var(--c-text-muted)', fontStyle: 'italic' }}>
                      {poet.quote}
                    </p>
                  )}
                </div>

                {/* Expanded bio */}
                {isExpanded && (
                  <div
                    className="px-6 pb-8"
                    onClick={(e) => e.stopPropagation()}
                    style={{ borderTop: `1px solid #1E1E52` }}
                  >
                    <div className="grid grid-cols-1 lg:grid-cols-3 gap-8 pt-6">
                      {/* Bio text */}
                      <div className="lg:col-span-2">
                        <blockquote
                          className="text-[16px] leading-[1.7] mb-6 pl-4"
                          style={{
                            fontFamily: 'var(--font-display)',
                            fontStyle: 'italic',
                            color: 'var(--c-text)',
                            borderLeft: `3px solid ${poet.color}`
                          }}
                        >
                          {poet.quote}
                        </blockquote>
                        {poet.bio.split('\n\n').map((para, i) => (
                          <p
                            key={i}
                            className="text-[15px] leading-[1.8] mb-4"
                            style={{ fontFamily: 'var(--font-body)', color: 'var(--c-text)' }}
                          >
                            {para}
                          </p>
                        ))}

                      </div>

                      {/* Works sidebar */}
                      <div className="lg:col-span-1">
                        <div
                          className="p-5 rounded-lg"
                          style={{ backgroundColor: 'var(--c-surface)' }}
                        >
                          <div
                            className="text-[11px] tracking-[0.15em] uppercase mb-4"
                            style={{ fontFamily: 'var(--font-body)', color: poet.color }}
                          >
                            Ключевые работы
                          </div>
                          <ul className="space-y-3">
                            {poet.works.map((work, i) => (
                              <li key={i} style={{ position: 'relative', paddingLeft: '14px' }}>
                                <span style={{ position: 'absolute', left: 0, top: '1px', color: poet.color, lineHeight: '1.5', fontSize: '16px' }}>·</span>
                                <span
                                  className="text-[14px] leading-[1.5]"
                                  style={{ fontFamily: 'var(--font-body)', color: 'var(--c-text-muted)', display: 'block' }}>
                                  {work}
                                </span>
                              </li>
                            ))}
                          </ul>
                        </div>
                      </div>
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
                        
